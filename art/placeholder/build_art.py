# Set 172: chosen placeholder tiles -> art/placeholder/tiles/*.png -> src/game/art.js (GAME_ART, data URIs).
# Usage (from repo root):
#   python3 -I art/placeholder/build_art.py --copy <crawl-tiles dir>   # copy picks from the CC0 tile repo, then write art.js
#   python3 -I art/placeholder/build_art.py                             # rewrite art.js from the committed tiles only
import sys, os, base64, shutil, importlib.util as u
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sp = u.spec_from_file_location('tables', os.path.join(HERE, 'tables.py')); t = u.module_from_spec(sp); sp.loader.exec_module(t)
TILES = os.path.join(HERE, 'tiles')

def picks():
    code = open(os.path.join(HERE, 'picks.txt'), encoding='utf-8').read().split()
    out = {}
    for w in code[1:]:
        k, _, v = w.partition(':')
        out[k] = v
    return out

def chosen():
    p = picks(); res = {}
    for group, table, pre in (('unit', t.PICK, ''), ('unit', t.BOSSES, ''), ('rune', t.RUNES, '')):
        for k, v in table.items():
            opts = v.split(); n = int(p.get(k, '1'))
            res[(group, k)] = opts[n - 1]
    for key, _, opts in t.SCENES:
        f, w = opts[1 if p.get(key) == 'B' else 0]
        res[('scene', key + '-floor')] = f; res[('scene', key + '-wall')] = w
    res[('ui', 'gold')] = 'item/gold/01'; res[('ui', 'heart')] = 'misc/icons/heart'
    return res

def copy(root):
    T = os.path.join(root, 'releases/Nov-2015')
    bad = set(l.strip().lstrip('- ').split('/')[-1][:-4] for l in open(os.path.join(root, 'TILES_UNDER_UNKNOWN_LICENSE.md')) if '.png' in l)
    idx, gidx = {}, {}
    for d, _, fs in os.walk(T):
        for f in fs:
            if f.endswith('.png'):
                idx.setdefault(f[:-4], os.path.join(d, f))
                if os.sep + 'gui' + os.sep in d + os.sep: gidx.setdefault(f[:-4], os.path.join(d, f))
    os.makedirs(TILES, exist_ok=True)
    for (g, k), n in chosen().items():
        if '/' in n:
            src = os.path.join(T, n + '.png')
            if not os.path.exists(src): src = os.path.join(T, 'gui', n + '.png')
        else:
            src = (gidx if g == 'rune' else idx).get(n)
        if not src or not os.path.exists(src): sys.exit('missing tile: ' + n)
        if os.path.basename(src)[:-4] in bad: sys.exit('unknown-licence tile: ' + n)
        shutil.copyfile(src, os.path.join(TILES, f'{g}-{k}.png'))

def write_js():
    groups = {}
    for (g, k) in chosen():
        p = os.path.join(TILES, f'{g}-{k}.png')
        data = open(p, 'rb').read()
        if data[:8] != b'\x89PNG\r\n\x1a\n': sys.exit('not a PNG: ' + p)
        groups.setdefault(g, {})[k] = 'data:image/png;base64,' + base64.b64encode(data).decode()
    lines = ['// Set 172: placeholder pixel art for the GAME PAGE ONLY (Balance Room / check keep coloured shapes).',
             '// Tiles: Dungeon Crawl Stone Soup (CC0 1.0, github.com/crawl/tiles) · generated by art/placeholder/build_art.py — do not edit by hand.',
             'export const GAME_ART = {']
    for g in ('unit', 'rune', 'scene', 'ui'):
        lines.append(f'  {g}: {{')
        for k, v in groups[g].items(): lines.append(f"    '{k}': '{v}',")
        lines.append('  },')
    lines.append('};')
    lines.append("// rune id -> art key (tribe runes D1-D6 / fields F1-F6 share one icon)")
    lines.append("export const runeArtKey = id => (/^[DF][1-6]$/.test(String(id)) ? String(id)[0] : String(id));")
    out = os.path.join(REPO, 'src', 'game', 'art.js')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print({g: len(v) for g, v in groups.items()}, 'bytes', os.path.getsize(out))

if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--copy': copy(sys.argv[2])
    write_js()
